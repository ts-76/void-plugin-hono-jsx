import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtemp,writeFile,readFile } from 'node:fs/promises';
import { join,resolve } from 'node:path';
import { tmpdir } from 'node:os';
const repo=resolve(import.meta.dirname,'..');
const root=await mkdtemp(join(tmpdir(),'hono-markdown-independent-'));
const run=(args,cwd=root)=>execFileSync('npm',args,{cwd,encoding:'utf8',maxBuffer:16*1024*1024});
const packed=JSON.parse(run(['pack','--ignore-scripts','--json','--pack-destination',root],join(repo,'packages/hono-markdown')));
await writeFile(join(root,'package.json'),'{"type":"module","private":true}');
run(['install','--ignore-scripts','--no-audit','--no-fund',join(root,packed[0].filename),'hono@4.13.13','markdown-exit@1.3.0','yaml@2.9.1','markdown-it-container@4.0.0','shiki@4.5.0','@shikijs/transformers@4.5.0']);
const check=String.raw`import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { writeFile } from 'node:fs/promises';
import { compileMarkdownModule, readMarkdownModule } from '@ts-76/hono-markdown/compiler';
const require=createRequire(import.meta.url);
for(const name of ['void','vite','void-plugin-hono-jsx'])assert.throws(()=>require.resolve(name));
const output=await compileMarkdownModule('---\ntitle: Independent\n---\n# Hono Markdown\n\n::: tip Advice\nWorks without Void\n:::',{sourcePath:process.cwd()+'/deck.md'});
assert.equal(output.frontmatter.title,'Independent');
assert.equal(output.headings[0].slug,'hono-markdown');
await writeFile(new URL('./slide.mjs',import.meta.url),output.code);
const page=await import('./slide.mjs');
const html=await page.default().toString();
assert.match(html,/<h1 id="hono-markdown">Hono Markdown<\/h1>/);
assert.match(html,/Works without Void/);
assert.throws(()=>readMarkdownModule('<script>window.bad=true;</script>\n# Bad'),/component imports only/);
console.log(JSON.stringify({root:process.cwd(),voidInstalled:false,viteInstalled:false,ssr:true,metadata:true,strictScripts:true}));`;
await writeFile(join(root,'check.mjs'),check);
console.log(execFileSync(process.execPath,[join(root,'check.mjs')],{cwd:root,encoding:'utf8'}));
