# Requires Python 3, agent-browser 0.19.0, and a running Chrome session named void-hono-pages.
import subprocess,json,time

def browser(*args):
 r=subprocess.run(['agent-browser','--session','void-hono-pages',*args],capture_output=True,text=True,check=True)
 return r.stdout.strip()
def evaluate(code): return browser('eval',code)
def expect(condition): evaluate('if(!('+condition+')) throw new Error('+json.dumps(condition)+'); true')
def idle():
 browser('wait','#app[data-navigation="idle"]')
 time.sleep(.1)
def click(id): browser('click','#'+id); idle()
for port in [5174,4174]:
 browser('open',f'http://127.0.0.1:{port}/users/alice')
 browser('wait','#app[data-hono-pages="mounted"]')
 browser('errors','--clear');browser('console','--clear')
 evaluate('window.documentMarker=123; true')
 click('nav-bob')
 expect('window.documentMarker===123 && document.querySelector("#route-value").textContent==="bob" && location.pathname==="/users/bob"')
 click('nav-alice')
 expect('window.documentMarker===123 && location.search==="?tab=profile" && document.querySelector("#route-value").textContent==="alice"')
 browser('back');idle()
 expect('document.querySelector("#route-value").textContent==="bob"')
 browser('forward');idle()
 expect('location.search==="?tab=profile" && document.querySelector("#route-value").textContent==="alice"')
 click('nav-hash')
 expect('location.hash==="#route-value" && window.documentMarker===123')
 evaluate('document.querySelector("#route-count").nextElementSibling.click(); true')
 expect('document.querySelector("#route-count").textContent==="1"')
 click('nav-refresh')
 expect('document.querySelector("#route-count").textContent==="1" && window.documentMarker===123')
 # Modified clicks and native destinations must not be intercepted. Prevent defaults later to avoid opening tabs/downloads.
 evaluate('window.addEventListener("click",e=>e.preventDefault(),{once:true}); const e=new MouseEvent("click",{bubbles:true,cancelable:true,ctrlKey:true}); window.nativeSeen=null; document.addEventListener("click",e=>window.nativeSeen=e.defaultPrevented,{once:true}); document.querySelector("#nav-bob").dispatchEvent(e); if(window.nativeSeen) throw new Error("Modified click intercepted"); true')
 for id in ['nav-external','nav-download','nav-reload']:
  evaluate('window.addEventListener("click",e=>e.preventDefault(),{once:true}); document.addEventListener("click",e=>window.nativeSeen=e.defaultPrevented,{once:true}); document.querySelector('+json.dumps('#'+id)+').click(); if(window.nativeSeen) throw new Error("Native link intercepted"); true')
 evaluate('document.querySelector("#nav-slow").click(); setTimeout(()=>document.querySelector("#nav-bob").click(),40); true')
 time.sleep(1);idle()
 expect('document.querySelector("#route-value").textContent==="bob" && location.pathname==="/users/bob" && window.documentMarker===123')
 evaluate('window.originalFetch=window.fetch; window.fetch=(url,options)=>String(url).includes("fail=1") ? Promise.resolve(new Response("invalid json",{headers:{"X-VoidPages":"true","Content-Type":"application/json"}})) : window.originalFetch(url,options); true')
 click('nav-failed')
 browser('wait','[role="alert"]')
 expect('document.querySelector("#route-value").textContent==="bob" && document.querySelector("#app").dataset.navigation==="idle"')
 evaluate('window.fetch=window.originalFetch; true')
 click('nav-alice')
 expect('!document.querySelector("[role=alert]") && document.querySelector("#route-value").textContent==="alice"')
 click('nav-browser')
 expect('document.querySelector("#browser-agent").textContent.length>0 && window.documentMarker===123')
 # Return by history because the client-only fixture intentionally has a native home link.
 browser('back');idle()
 click('nav-reload');browser('wait','#app[data-hono-pages="mounted"]')
 expect('window.documentMarker===undefined && location.pathname==="/about"')
 assert not browser('errors'),browser('errors')
 print(f'Navigation, history, query/hash, preserved refresh, native anchors, cancellation, failure recovery, client-only navigation and document reload passed: {port}',flush=True)
